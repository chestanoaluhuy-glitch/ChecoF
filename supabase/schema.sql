/*
   Semua pengunjung boleh melihat produk.
*/

drop policy if exists
"Public can read products"
on public.products;


create policy
"Public can read products"
on public.products

for select

to anon, authenticated

using (
    true
);


/*
   Admin boleh menambah produk.
*/

drop policy if exists
"Admin can insert products"
on public.products;


create policy
"Admin can insert products"
on public.products

for insert

to authenticated

with check (
    exists (
        select 1
        from public.profiles
        where profiles.id = auth.uid()
        and profiles.role = 'admin'
    )
);


