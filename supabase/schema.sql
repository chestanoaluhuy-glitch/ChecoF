/* =========================================================
   11. CHECKOUT FUNCTION
   create_ardana_order
========================================================= */

drop function if exists
public.create_ardana_order(
    text,
    text,
    text,
    jsonb
);


create or replace function
public.create_ardana_order(
    p_customer_name text,
    p_phone text,
    p_notes text,
    p_items jsonb
)

returns jsonb

language plpgsql

security definer

set search_path = public

as $$

declare

    v_user_id uuid;

    v_order_id bigint;

    v_order_number text;

    v_total numeric(12, 2) := 0;

    v_item jsonb;

    v_product_id bigint;

    v_product_name text;

    v_price numeric(12, 2);

    v_quantity integer;

    v_stock integer;

    v_subtotal numeric(12, 2);

begin

    /* =====================================================
       CEK USER LOGIN
    ===================================================== */

    v_user_id := auth.uid();


    if v_user_id is null then

        raise exception
            'Kamu harus login terlebih dahulu.';

    end if;


    /* =====================================================
       VALIDASI CUSTOMER
    ===================================================== */

    if trim(coalesce(p_customer_name, '')) = '' then

        raise exception
            'Nama customer wajib diisi.';

    end if;


    if trim(coalesce(p_phone, '')) = '' then

        raise exception
            'Nomor WhatsApp wajib diisi.';

    end if;


    /* =====================================================
       VALIDASI CART
    ===================================================== */

    if p_items is null
       or jsonb_array_length(p_items) = 0 then

        raise exception
            'Keranjang masih kosong.';

    end if;


    /* =====================================================
       BUAT NOMOR ORDER
    ===================================================== */

    v_order_number :=
        'ARD-' ||
        to_char(
            now(),
            'YYYYMMDDHH24MISS'
        ) ||
        '-' ||
        floor(
            random() * 1000
        )::text;


    /* =====================================================
       INSERT ORDER AWAL
    ===================================================== */

    insert into public.orders (

        order_number,
        customer_name,
        phone,
        notes,
        total,
        status,
        user_id

    )

    values (

        v_order_number,
        trim(p_customer_name),
        trim(p_phone),
        nullif(
            trim(coalesce(p_notes, '')),
            ''
        ),
        0,
        'pending',
        v_user_id

    )

    returning id
    into v_order_id;


    /* =====================================================
       PROSES SETIAP ITEM
    ===================================================== */

    for v_item in
        select *
        from jsonb_array_elements(p_items)

    loop

        v_product_id :=
            (v_item ->> 'product_id')::bigint;


        v_quantity :=
            (v_item ->> 'quantity')::integer;


        if v_quantity is null
           or v_quantity <= 0 then

            raise exception
                'Jumlah produk tidak valid.';

        end if;


        /* =================================================
           LOCK PRODUCT
        ================================================= */

        select
            name,
            price,
            stock

        into
            v_product_name,
            v_price,
            v_stock

        from public.products

        where id = v_product_id

        for update;


        if not found then

            raise exception
                'Produk dengan ID % tidak ditemukan.',
                v_product_id;

        end if;


        /* =================================================
           CEK STOCK
        ================================================= */

        if v_stock < v_quantity then

            raise exception
                'Stock produk "%" tidak mencukupi.',
                v_product_name;

        end if;


        /* =================================================
           HITUNG SUBTOTAL
        ================================================= */

        v_subtotal :=
            v_price * v_quantity;


        v_total :=
            v_total + v_subtotal;


        /* =================================================
           SIMPAN ORDER ITEM
        ================================================= */

        insert into public.order_items (

            order_id,
            product_id,
            product_name,
            price,
            quantity,
            subtotal

        )

        values (

            v_order_id,
            v_product_id,
            v_product_name,
            v_price,
            v_quantity,
            v_subtotal

        );


        /* =================================================
           KURANGI STOCK
        ================================================= */

        update public.products

        set stock =
            stock - v_quantity

        where id = v_product_id;


    end loop;


    /* =====================================================
       UPDATE TOTAL ORDER
    ===================================================== */

    update public.orders

    set total = v_total

    where id = v_order_id;


    /* =====================================================
       RETURN RESULT
    ===================================================== */

    return jsonb_build_object(

        'success',
        true,

        'order_id',
        v_order_id,

        'order_number',
        v_order_number,

        'total',
        v_total

    );


exception

    when others then

        /*
           Jika terjadi error,
           seluruh transaksi akan rollback.
        */

        raise;

end;

$$;


